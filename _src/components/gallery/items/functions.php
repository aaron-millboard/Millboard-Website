<?php

namespace Granola\Components\Gallery\Items;

function filter_args(array $args): ?array
{
    // -------------------------------------------------------------------------
    // Default arguments.
    // -------------------------------------------------------------------------
    $args = array_merge([
        'classes' => [],
        'images' => [],
    ], $args);

    // -------------------------------------------------------------------------
    // Required classes.
    // -------------------------------------------------------------------------
    $args['classes'] = array_merge([
        'gallery__list',
        'list-reset--hard',
    ], $args['classes']);

    // -------------------------------------------------------------------------
    // Bail early - return null for no output.
    // -------------------------------------------------------------------------
    if (empty($args['images'])) {
         return null;
    }

    // -------------------------------------------------------------------------
    // Return the filtered args.
    // -------------------------------------------------------------------------
    return $args;
}
